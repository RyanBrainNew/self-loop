import { appendAudit, emptyState, nowIso } from './store.mjs';

const MINUTE = 60_000;
const ago = (now, minutes) => nowIso(now - minutes * MINUTE);

function event({
  id,
  sourceId,
  sourceName,
  sourceKind,
  kind,
  title,
  body,
  actor = 'connector',
  externalId,
  priority = 'normal',
  labels = [],
  acceptance = [],
  scope = [],
  risk = 'medium',
  status = 'consumed',
  receivedAt,
  consumedAt = receivedAt,
  ticketId = null,
  ignoredReason = null,
}) {
  return {
    id,
    sourceId,
    sourceName,
    sourceKind,
    kind,
    title,
    body,
    actor,
    externalId,
    dedupeKey: `${sourceId}:${kind}:${externalId}`,
    priority,
    labels,
    acceptance,
    scope,
    risk,
    status,
    receivedAt,
    consumedAt: status === 'pending' ? null : consumedAt,
    ticketId,
    ignoredReason,
  };
}

function ticket({
  id,
  number,
  sourceId,
  sourceName,
  sourceKind,
  externalId,
  title,
  summary,
  state,
  priority = 'normal',
  labels = [],
  acceptance = [],
  scope = [],
  risk = 'medium',
  sourceEventId,
  createdAt,
  updatedAt,
  attempts,
  maxAttempts = 2,
  workerId = null,
  workerName = null,
  lease = null,
  pr = null,
  humanQuestion = null,
  humanAnswer = null,
  lastError = null,
  flaky = false,
  failAlways = false,
  currentAttemptId = null,
}) {
  return {
    id,
    number,
    projectId: 'prj_selfloop',
    sourceId,
    sourceName,
    sourceKind,
    externalId,
    title,
    summary,
    state,
    priority,
    labels,
    acceptance,
    scope,
    risk,
    sourceEventId,
    createdAt,
    updatedAt,
    attempts,
    maxAttempts,
    workerId,
    workerName,
    lease,
    currentAttemptId,
    pr,
    humanQuestion,
    humanAnswer,
    lastError,
    flaky,
    failAlways,
    approvedAt: null,
    approvedBy: null,
  };
}

function attempt({
  id,
  ticketRef,
  number,
  workerId,
  workerName,
  state,
  phase,
  startedAt,
  phaseAt = startedAt,
  finishedAt = null,
  evidence = [],
  error = null,
}) {
  return {
    id,
    ticketId: ticketRef.id,
    ticketNumber: ticketRef.number,
    number,
    workerId,
    workerName,
    state,
    phase,
    startedAt,
    phaseAt,
    finishedAt,
    evidence,
    error,
  };
}

function delivery({
  id,
  ticketRef,
  channel,
  target,
  kind,
  state,
  attempts,
  maxAttempts = 3,
  createdAt,
  nextAttemptAt = null,
  sentAt = null,
  lastAttemptAt = null,
  lastError = null,
  failFirst = false,
  failAlways = false,
  failure = null,
}) {
  return {
    id,
    ticketId: ticketRef.id,
    ticketNumber: ticketRef.number,
    channel,
    target,
    kind,
    state,
    attempts,
    maxAttempts,
    createdAt,
    nextAttemptAt,
    sentAt,
    lastAttemptAt,
    lastError,
    idempotencyKey: `${ticketRef.id}:${kind}:${attempts}`,
    failFirst,
    failAlways,
    failure,
  };
}

function audit(state, at, entry) {
  appendAudit(state, entry, Date.parse(at));
}

